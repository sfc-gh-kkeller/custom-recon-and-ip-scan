USE ROLE ACCOUNTADMIN;
USE DATABASE <YOUR_DB>;
USE WAREHOUSE <YOUR_WAREHOUSE>;
CREATE SCHEMA IF NOT EXISTS TRUST_SCANNER;
USE SCHEMA TRUST_SCANNER;

CREATE OR REPLACE NOTIFICATION INTEGRATION TRUST_SCANNER_EMAIL_INT
  TYPE = EMAIL ENABLED = TRUE
  ALLOWED_RECIPIENTS = ('<YOUR_VERIFIED_EMAIL>');

CREATE OR REPLACE TABLE SCANNER_CONFIG (
  LOOKBACK_HOURS      NUMBER DEFAULT 24,
  RECON_DISTINCT_MIN  NUMBER DEFAULT 5,
  IP_DISTINCT_MIN     NUMBER DEFAULT 3,
  RECIPIENT           VARCHAR DEFAULT '<YOUR_VERIFIED_EMAIL>',
  EMAIL_INTEGRATION   VARCHAR DEFAULT 'TRUST_SCANNER_EMAIL_INT'
);
INSERT INTO SCANNER_CONFIG SELECT 24, 5, 3, '<YOUR_VERIFIED_EMAIL>', 'TRUST_SCANNER_EMAIL_INT';

CREATE OR REPLACE TABLE FINDINGS (
  FINDING_ID  VARCHAR DEFAULT UUID_STRING(),
  SCANNER_ID  VARCHAR,
  SEVERITY    VARCHAR,
  ENTITY      VARCHAR,
  SUMMARY     VARCHAR,
  DETAILS     VARIANT,
  DETECTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  NOTIFIED    BOOLEAN DEFAULT FALSE
);

CREATE OR REPLACE VIEW V_SYSTEM_USERS AS
SELECT NAME FROM SNOWFLAKE.ACCOUNT_USAGE.USERS
WHERE DELETED_ON IS NULL AND TYPE IN ('SERVICE','LEGACY_SERVICE');

CREATE OR REPLACE PROCEDURE SCAN(P_ALL_USERS BOOLEAN DEFAULT FALSE)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  lb NUMBER; rmin NUMBER; imin NUMBER; rcpt VARCHAR; integ VARCHAR;
  new_cnt NUMBER DEFAULT 0; body VARCHAR;
BEGIN
  SELECT LOOKBACK_HOURS, RECON_DISTINCT_MIN, IP_DISTINCT_MIN, RECIPIENT, EMAIL_INTEGRATION
    INTO :lb, :rmin, :imin, :rcpt, :integ FROM SCANNER_CONFIG LIMIT 1;

  -- Scanner 1: reconnaissance by system users (breadth of metadata enumeration)
  INSERT INTO FINDINGS (SCANNER_ID, SEVERITY, ENTITY, SUMMARY, DETAILS)
  SELECT 'RECON_SYSTEM_USER', IFF(kinds >= :rmin * 2, 'HIGH', 'MEDIUM'), user_name,
         'System user ran ' || total || ' reconnaissance queries across ' || kinds || ' object types',
         OBJECT_CONSTRUCT('kinds', kind_list, 'first_seen', first_seen, 'last_seen', last_seen, 'sample_roles', roles)
  FROM (
    SELECT q.USER_NAME AS user_name, COUNT(*) AS total,
           COUNT(DISTINCT kind) AS kinds, ARRAY_AGG(DISTINCT kind) AS kind_list,
           MIN(q.START_TIME) AS first_seen, MAX(q.START_TIME) AS last_seen,
           ARRAY_AGG(DISTINCT q.ROLE_NAME) AS roles
    FROM (
      SELECT USER_NAME, START_TIME, ROLE_NAME,
             COALESCE(UPPER(REGEXP_SUBSTR(QUERY_TEXT, '(SHOW|DESCRIBE|DESC)\\s+[A-Za-z_]+(\\s+[A-Za-z_]+)?', 1, 1, 'i')),
                      'METADATA_VIEW') AS kind
      FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
      WHERE START_TIME >= DATEADD('hour', -:lb, CURRENT_TIMESTAMP())
        AND ( REGEXP_LIKE(QUERY_TEXT, '\\s*(SHOW|DESCRIBE|DESC)\\s+(USERS|ROLES|GRANTS|WAREHOUSES|DATABASES|SCHEMAS|TABLES|INTEGRATIONS|NETWORK|SHARES|STAGES|SECRETS|PARAMETERS|SECURITY|STORAGE|API|MANAGED|EXTERNAL|FUNCTIONS|PROCEDURES|TASKS|PIPES|STREAMS|VIEWS|COLUMNS).*', 'is')
           OR REGEXP_LIKE(QUERY_TEXT, '.*(ACCOUNT_USAGE|INFORMATION_SCHEMA)\\.(USERS|ROLES|GRANTS_TO_\\w+|GRANTS_ON_\\w+|LOGIN_HISTORY|SESSIONS|DATABASES|TABLES|COLUMNS|NETWORK_POLICIES|INTEGRATIONS)\\b.*', 'is') )
    ) q
    WHERE :P_ALL_USERS OR q.USER_NAME IN (SELECT NAME FROM V_SYSTEM_USERS)
    GROUP BY q.USER_NAME
    HAVING COUNT(DISTINCT kind) >= :rmin
  ) r
  WHERE NOT EXISTS (SELECT 1 FROM FINDINGS f WHERE f.SCANNER_ID = 'RECON_SYSTEM_USER' AND f.ENTITY = r.user_name
                    AND f.DETECTED_AT >= DATEADD('hour', -:lb, CURRENT_TIMESTAMP()));

  -- Scanner 2: frequent logins from many distinct IPs
  INSERT INTO FINDINGS (SCANNER_ID, SEVERITY, ENTITY, SUMMARY, DETAILS)
  SELECT 'MULTI_IP_LOGIN', IFF(ips >= :imin * 2, 'HIGH', 'MEDIUM'), user_name,
         logins || ' successful logins from ' || ips || ' distinct IPs',
         OBJECT_CONSTRUCT('ips', ip_list, 'first_seen', first_seen, 'last_seen', last_seen,
                          'is_system_user', is_sys)
  FROM (
    SELECT l.USER_NAME AS user_name, COUNT(*) AS logins, COUNT(DISTINCT l.CLIENT_IP) AS ips,
           ARRAY_AGG(DISTINCT l.CLIENT_IP) AS ip_list,
           MIN(l.EVENT_TIMESTAMP) AS first_seen, MAX(l.EVENT_TIMESTAMP) AS last_seen,
           MAX(IFF(s.NAME IS NOT NULL, TRUE, FALSE)) AS is_sys
    FROM SNOWFLAKE.ACCOUNT_USAGE.LOGIN_HISTORY l
    LEFT JOIN V_SYSTEM_USERS s ON s.NAME = l.USER_NAME
    WHERE l.IS_SUCCESS = 'YES' AND l.EVENT_TIMESTAMP >= DATEADD('hour', -:lb, CURRENT_TIMESTAMP())
    GROUP BY l.USER_NAME
    HAVING COUNT(DISTINCT l.CLIENT_IP) >= :imin
  ) m
  WHERE NOT EXISTS (SELECT 1 FROM FINDINGS f WHERE f.SCANNER_ID = 'MULTI_IP_LOGIN' AND f.ENTITY = m.user_name
                    AND f.DETECTED_AT >= DATEADD('hour', -:lb, CURRENT_TIMESTAMP()));

  SELECT COUNT(*) INTO :new_cnt FROM FINDINGS WHERE NOT NOTIFIED;
  IF (new_cnt > 0) THEN
    SELECT LISTAGG('[' || SEVERITY || '] ' || SCANNER_ID || ' | ' || ENTITY || ' | ' || SUMMARY || ' | ' || TO_VARCHAR(DETAILS), '\n')
      INTO :body FROM FINDINGS WHERE NOT NOTIFIED;
    CALL SYSTEM$SEND_EMAIL(:integ, :rcpt, 'Custom Trust Scanner: ' || :new_cnt || ' suspicious finding(s)', :body);
    UPDATE FINDINGS SET NOTIFIED = TRUE WHERE NOT NOTIFIED;
  END IF;
  RETURN 'new findings notified: ' || new_cnt;
END;
$$;

CREATE OR REPLACE TASK SCAN_TASK
  WAREHOUSE = <YOUR_WAREHOUSE>
  SCHEDULE = '60 MINUTE'
AS CALL SCAN(FALSE);
ALTER TASK SCAN_TASK RESUME;
