-- Alerts on new data movement policy violations (PROGRAMMATIC_FETCH, COPY, UI, agent).
-- Requires ACCOUNTADMIN (IMPORTED PRIVILEGES on SNOWFLAKE) and the email integration from 01_deploy.sql.
-- ACCOUNT_USAGE.DATA_MOVEMENT_VIOLATIONS has up to 3 hours of latency.
USE ROLE ACCOUNTADMIN;
USE DATABASE <YOUR_DB>;
CREATE SCHEMA IF NOT EXISTS DMP_DEMO;
USE SCHEMA DMP_DEMO;

CREATE OR REPLACE TABLE DMP_ALERT_STATE (LAST_SEEN TIMESTAMP_LTZ);
INSERT INTO DMP_ALERT_STATE SELECT DATEADD('hour', -24, CURRENT_TIMESTAMP());

CREATE OR REPLACE PROCEDURE DMP_NOTIFY_VIOLATIONS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  body VARCHAR;
  latest TIMESTAMP_LTZ;
BEGIN
  SELECT LISTAGG(
           '[' || EVENT_TIME || '] ' || MOVEMENT_TYPE || ' by ' || USER_NAME
           || ' query=' || QUERY_ID
           || ' enforced=' || COALESCE(ENFORCED_POLICY, 'none')
           || ' alerted=' || COALESCE(ALERTED_POLICIES, 'none'),
           '\n')
    INTO :body
    FROM TABLE(RESULT_SCAN(SNOWFLAKE.ALERT.GET_CONDITION_QUERY_UUID()));
  SELECT MAX(RAW_TS) INTO :latest
    FROM TABLE(RESULT_SCAN(SNOWFLAKE.ALERT.GET_CONDITION_QUERY_UUID()));
  CALL SYSTEM$SEND_EMAIL('TRUST_SCANNER_EMAIL_INT', '<YOUR_VERIFIED_EMAIL>',
                         'Data movement policy violation detected', :body);
  UPDATE DMP_ALERT_STATE SET LAST_SEEN = :latest;
  RETURN 'notified';
END;
$$;

CREATE OR REPLACE ALERT DMP_VIOLATION_ALERT
  WAREHOUSE = <YOUR_WAREHOUSE>
  SCHEDULE = '60 MINUTE'
  IF (EXISTS (
    SELECT v.QUERY_ID,
           v.USER_NAME,
           v.MOVEMENT_TYPE,
           TO_VARCHAR(v.ENFORCED_POLICY) AS ENFORCED_POLICY,
           TO_VARCHAR(v.ALERTED_POLICIES) AS ALERTED_POLICIES,
           TO_VARCHAR(v.TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS') AS EVENT_TIME,
           v.TIMESTAMP AS RAW_TS
    FROM SNOWFLAKE.ACCOUNT_USAGE.DATA_MOVEMENT_VIOLATIONS v
    WHERE v.TIMESTAMP > (SELECT MAX(LAST_SEEN) FROM <YOUR_DB>.DMP_DEMO.DMP_ALERT_STATE)
  ))
  THEN CALL <YOUR_DB>.DMP_DEMO.DMP_NOTIFY_VIOLATIONS();
